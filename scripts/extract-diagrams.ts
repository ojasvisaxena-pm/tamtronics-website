/**
 * Copies the original inline SVG artwork out of the HTML site into src/diagrams/data.ts, byte for byte.
 * Run only when the source artwork changes: npm run extract:diagrams
 */
import fs from 'node:fs'
import path from 'node:path'

const htmlDir = process.env.HTML_DIR || path.resolve(process.cwd(), '../tamtronics-html')
const read = (page: string) => fs.readFileSync(path.join(htmlDir, `${page}.html`), 'utf8')

type Svg = { raw: string; open: string; inner: string }

const svgsIn = (html: string): Svg[] =>
  [...html.matchAll(/<svg\b([^>]*)>([\s\S]*?)<\/svg>/g)].map((m) => ({ raw: m[0], open: m[1], inner: m[2] }))

const index = svgsIn(read('index'))
const platform = svgsIn(read('platform'))
const impl = svgsIn(read('first-implementation'))
const industries = svgsIn(read('industries'))

const find = (list: Svg[], needle: string): Svg => {
  const hit = list.find((s) => s.raw.includes(needle))
  if (!hit) throw new Error(`No SVG contains ${needle}`)
  return hit
}
const withBox = (list: Svg[], box: string) => list.filter((s) => s.open.includes(`viewBox="${box}"`))

const layerIcons = withBox(platform, '0 0 64 64')
const glyphs = withBox(impl, '0 0 260 44')
const industryArt = withBox(industries, '0 0 500 400')

const chosen: Record<string, Svg> = {
  'hero-connected': find(index, 'hero-svg-t'),
  architecture: find(index, 'arch-svg-t'),
  'signal-tile': find(index, 'Animated wireless signal'),
  'tile-healthcare': find(index, 'hhea-p0'),
  'tile-manufacturers': find(index, 'hmfg-p0'),
  'tile-rental': find(index, 'hren-p0'),
  'industry-healthcare': industryArt[0],
  'industry-manufacturers': industryArt[1],
  'industry-rental': industryArt[2],
  'fleet-scene': find(platform, 'each marked active, idle, or offline'),
  'iot-scene': find(impl, 'picks up activity from the equipment'),
  relation: find(impl, 'rel-t'),
  'layer-icon-equipment': layerIcons[0],
  'layer-icon-connectivity': layerIcons[1],
  'layer-icon-application': layerIcons[2],
  'layer-icon-data': layerIcons[3],
  'glyph-session': glyphs[0],
  'glyph-duration': glyphs[1],
  'glyph-power': glyphs[2],
  'glyph-connectivity': glyphs[3],
}

// Every copy of a shared diagram across pages must be identical, or one page would silently change.
const assertSame = (name: string, list: Svg[], needle: string) => {
  for (const s of list.filter((x) => x.raw.includes(needle))) {
    if (s.raw !== chosen[name].raw) throw new Error(`${name} differs between pages`)
  }
}
assertSame('architecture', platform, 'arch-svg-t')
assertSame('signal-tile', [...platform, ...impl], 'Animated wireless signal')
assertSame('fleet-scene', impl, 'each marked active, idle, or offline')

const parseAttrs = (open: string) =>
  Object.fromEntries([...open.matchAll(/([\w:-]+)(?:="([^"]*)")?/g)].map((m) => [m[1] === 'class' ? 'className' : m[1], m[2] ?? '']))

const out = Object.fromEntries(
  Object.entries(chosen).map(([name, svg]) => [name, { attrs: parseAttrs(svg.open), inner: svg.inner }]),
)

// Anything not captured here would be missing from the CMS-rendered pages.
const known = new Set(Object.values(chosen).map((s) => s.raw))
for (const [page, list] of Object.entries({ index, platform, impl, industries })) {
  for (const s of list) {
    if (!known.has(s.raw) && s.raw.length > 700) console.warn(`Uncaptured SVG on ${page}: ${s.raw.slice(0, 120)}`)
  }
}

const target = path.resolve(process.cwd(), 'src/diagrams/data.ts')
fs.mkdirSync(path.dirname(target), { recursive: true })
fs.writeFileSync(
  target,
  `/* GENERATED by scripts/extract-diagrams.ts from the original HTML. Do not edit by hand. */\n` +
    `export const diagramData: Record<string, { attrs: Record<string, string>; inner: string }> = ${JSON.stringify(out, null, 2)}\n`,
)
console.log(`Wrote ${Object.keys(out).length} diagrams to ${target}`)
